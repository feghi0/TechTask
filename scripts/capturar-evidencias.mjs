import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const dir=resolve('docs/entrega-tp4/03-evidencias/capturas');
mkdirSync(dir,{recursive:true});
const db=resolve(`data/capturas-${Date.now()}.sqlite`);
mkdirSync(resolve('data'),{recursive:true});
const api=spawn(process.execPath,['--import','tsx','backend/src/server.ts'],{env:{...process.env,DATABASE_PATH:db},stdio:['ignore','pipe','pipe']});
const web=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5180','--strictPort'],{stdio:['ignore','pipe','pipe']});
let logs='';for(const proc of [api,web]) for(const stream of [proc.stdout,proc.stderr]) stream.on('data',b=>{logs+=b.toString();});
async function ready(url) {for(let i=0;i<100;i++){try{if((await fetch(url)).ok)return;}catch{}await new Promise(r=>setTimeout(r,200));}throw Error(`Servidor no disponible: ${url}`);}
await Promise.all([ready('http://127.0.0.1:3001/api/tasks'),ready('http://127.0.0.1:5180')]);
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const transactions=[];
async function post(body){const r=await fetch('http://127.0.0.1:3001/api/tasks',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});if(r.status!==201)throw Error('Falló creación de demostración');transactions.push({method:'POST',url:r.url,status:r.status,request:body,response:await r.json()});}
await post({title:'Proyecto de Base de Datos',subject:'Base de Datos',description:'Diseñar las tablas y documentar sus relaciones.',status:'in_progress',priority:'high',dueDate:'2026-11-19'});
await post({title:'Entrega de Programación',subject:'Programación',description:'Entrega de ejemplo creada directamente con este estado; no demuestra una transición.',status:'delivered',priority:'medium'});
await page.goto('http://127.0.0.1:5180');
await page.getByRole('heading',{name:'Proyecto de Base de Datos',exact:true}).waitFor();
await page.screenshot({path:`${dir}/01-dashboard.png`,fullPage:true});
await page.getByRole('button',{name:'Nueva tarea',exact:true}).click();
await page.getByLabel('Título *').fill('TP de Redes');
await page.getByLabel('Materia *').fill('Redes');
await page.getByLabel('Descripción').fill('Documentar la topología de red del laboratorio.');
await page.getByLabel('Prioridad').selectOption('high');
await page.getByLabel('Fecha de entrega').fill('2026-11-18');
await page.getByRole('checkbox',{name:'Marcar como favorita',exact:true}).check();
await page.screenshot({path:`${dir}/02-formulario.png`,fullPage:true});
const postPromise=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/api/tasks'));
await page.getByRole('button',{name:'Guardar tarea'}).click();
const created=await postPromise;const createdJson=await created.json();if(created.status()!==201)throw Error('POST no devolvió 201');
transactions.push({method:'POST',url:created.url(),status:created.status(),request:created.request().postDataJSON(),response:createdJson});
await page.getByText('Tarea guardada en el servidor.',{exact:true}).waitFor();
await page.getByRole('heading',{name:'TP de Redes',exact:true}).waitFor();
await page.screenshot({path:`${dir}/03-tarea-creada.png`,fullPage:true});
await page.getByLabel('Título *').fill('ab');await page.getByLabel('Materia *').fill('Redes');
// Omite solo la restricción HTML para ejercitar la validación real del backend.
await page.locator('form').evaluate(form=>form.noValidate=true);
const invalidPromise=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/api/tasks'));
await page.getByRole('button',{name:'Guardar tarea'}).click();
const invalid=await invalidPromise;if(invalid.status()!==400)throw Error('No se rechazó el título');
transactions.push({method:'POST',url:invalid.url(),status:invalid.status(),request:invalid.request().postDataJSON(),response:await invalid.json()});
await page.getByRole('alert').filter({hasText:'Debe tener entre 3 y 60 caracteres.'}).waitFor();
await page.screenshot({path:`${dir}/04-validacion.png`,fullPage:true});
const getPromise=page.waitForResponse(r=>r.request().method()==='GET'&&r.url().endsWith('/api/tasks'));
await page.reload();const listed=await getPromise;const listedJson=await listed.json();
if(!listedJson.data.some(t=>t.id===createdJson.data.id&&t.title==='TP de Redes'))throw Error('No persiste la tarea');
await page.getByRole('heading',{name:'TP de Redes',exact:true}).waitFor();
await page.screenshot({path:`${dir}/07-persistencia.png`,fullPage:true});
transactions.push({method:'GET',url:listed.url(),status:listed.status(),response:listedJson});
writeFileSync(`${dir}/transacciones.json`,JSON.stringify(transactions,null,2));
writeFileSync(`${dir}/ejecucion.json`,JSON.stringify({date:new Date().toISOString(),database:db,viewport:{width:1600,height:1050},createdId:createdJson.data.id,persistedId:listedJson.data.find(t=>t.id===createdJson.data.id).id,consoleErrors:errors,expectedConsoleError:'HTTP 400 durante la prueba negativa'},null,2));
writeFileSync(`${dir}/servidores.txt`,logs);
console.log('CAPTURAS DE INTERFAZ VERIFICADAS. Base de demostración:',db);
await browser.close();
// Los servidores permanecen activos para capturar peticiones HTTP reales en terminal.
writeFileSync(`${dir}/procesos.json`,JSON.stringify({api:api.pid,web:web.pid}));
console.log('Servidores activos: API 3001 / frontend 5180.');
